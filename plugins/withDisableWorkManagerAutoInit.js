/**
 * Config plugin: disable androidx WorkManager auto-initialization.
 *
 * WorkManager ships an androidx.startup InitializationProvider Component that
 * auto-creates its Room `WorkDatabase` during ContentProvider.attachInfo --
 * before any React Native code runs. On some Android devices/emulators this
 * fails with:
 *
 *   java.lang.RuntimeException: Unable to get provider
 *   androidx.startup.InitializationProvider
 *   Caused by: Failed to create an instance of class
 *   androidx.work.impl.WorkDatabase.canonicalName
 *
 * Fix: remove the WorkManagerInitializer meta-data entry from
 * androidx.startup.InitializationProvider, so WorkManager is not
 * auto-initialised at app start.
 *
 * Requires android/ to be regenerated by `expo prebuild` each build, so this
 * plugin persists across Continuous Native Generation.
 */

const withDisableWorkManagerAutoInit = (config) => {
  config.mods = config.mods || {};
  const originalAndroidManifest = config.mods.androidManifest;
  config.mods.androidManifest = async (manifestConfig) => {
    let manifest = await (originalAndroidManifest
      ? originalAndroidManifest(manifestConfig)
      : manifestConfig);

    const root = manifest.modResults && manifest.modResults.manifest;
    if (!root) return manifest;

    // Declare the tools namespace on the <manifest> root.
    if (!root.$) root.$ = {};
    if (!root.$['xmlns:tools']) {
      root.$['xmlns:tools'] = 'http://schemas.android.com/tools';
    }

    // Allow cleartext HTTP to the LAN backend (Android 9+ blocks it by default).
    const application = root.application;
    const app = application && Array.isArray(application) ? application[0] : null;
    if (app && app.$) {
      app.$['android:usesCleartextTraffic'] = 'true';
    }

    // Remove WorkManagerInitializer from InitializationProvider components.
    if (app && app.provider) {
      const providers = Array.isArray(app.provider) ? app.provider : [app.provider];
      for (const provider of providers) {
        const manifestProvider = provider.$;
        if (!manifestProvider) continue;
        const name = manifestProvider['android:name'];
        if (!name || !name.includes('InitializationProvider')) continue;

        if (!provider['meta-data']) provider['meta-data'] = [];
        const hasWorkManager = provider['meta-data'].some((md) => {
          const m = md.$;
          return m && m['android:name'] === 'androidx.work.WorkManagerInitializer';
        });

        if (!hasWorkManager) {
          provider['meta-data'].push({
            $: {
              'android:name': 'androidx.work.WorkManagerInitializer',
              'android:value': 'androidx.startup',
              'tools:node': 'remove',
            },
          });
        } else {
          for (const md of provider['meta-data']) {
            const m = md.$;
            if (m && m['android:name'] === 'androidx.work.WorkManagerInitializer') {
              m['tools:node'] = 'remove';
            }
          }
        }
      }
    }

    return manifest;
  };

  return config;
};

export default withDisableWorkManagerAutoInit;
